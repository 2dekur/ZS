const DICTS: Record<Lang, Record<Key, string>> = { en, fr }

export const langAtom = atomWithStorage<Lang>(
  'zs.lang',
  navigator.language.toLowerCase().startsWith('fr') ? 'fr' : 'en',
  undefined,
  { getOnInit: true },
)

export type T = (key: Key, vars?: Record<string, string | number>) => string

const SINGULAR: Record<Lang, Partial<Record<Key, string>>> = {
  en: { 'lib.songs': '1 song', 'col.songs': '1 song' },
  fr: { 'lib.songs': '1 titre', 'col.songs': '1 titre' },
}

function format(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  const s = (vars?.n === 1 && SINGULAR[lang][key]) || DICTS[lang][key] || en[key]
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? '')) : s
}

export function useT(): T {
  const lang = useAtomValue(langAtom)
  return useCallback((key, vars) => format(lang, key, vars), [lang])
}

// For code outside React (store actions, audio controller).
export const tr: T = (key, vars) => format(getDefaultStore().get(langAtom), key, vars)
